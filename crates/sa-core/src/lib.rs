//! Engine core of the 1:1 rebuild of `gta_sa.exe` 1.0 US, and the foundation every port uses
//! (`docs/arch/ADR-001-globals-and-layouts.md`):
//!
//! - [`mem`]: game globals ([`mem::Global`], declared with [`globals!`]). Phase A: the original's
//!   fixed addresses. Phases B/C: Rust-owned storage. The same port source works in both.
//! - [`orig`]: typed calls to functions that may still be original ([`orig!`]). Phase A: through the
//!   original address, so the hook table decides Rust vs. original. Phases B/C: straight to Rust.
//! - [`abi`]: hook registration records ([`abi::HookReg`], emitted by `#[hook]`), calling
//!   conventions, return-value conversion, the FPU guard of the hook shims.
//! - [`layouts`]: sizes and offsets from `catalog/layouts.csv` (generated) with const assertions.
//! - Ports (CORE pilots, state `implemented`, see `docs/arch/pilot-ports.md`): [`pool`] (`CPool<T>`
//!   for peds, vehicles, objects), [`timer`] (`CTimer` except `Update`), [`general`]
//!   (`CGeneral::GetRandomNumberInRange`), [`crt`] (`rand`).
//! - [`hooks`]: the explicit list of every `#[hook]` in this crate, collected by `sa-hook`.
//!
//! Phase A is `cfg(sa_phase_a)` = feature `in-process` on 32-bit x86 Windows (set by build.rs).
//! Every other build (host tests, wasm32, a future phase B) uses Rust-owned memory. All raw
//! memory access of the crate is in [`mem`]; port modules use its safe accessors.
#![no_std]
// Raw memory access and FFI only in `mem`, `orig`, `abi` (and the expansions of their macros).
