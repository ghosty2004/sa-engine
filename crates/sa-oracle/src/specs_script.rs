// ------------------------------------------------------------------ operand stream generator

#[derive(Clone, Copy, PartialEq, Eq)]
enum Mode {
    /// `CollectParameters`, `CollectNextParameterWithoutIncreasingPC`: 1/6 dword, 2/3 variable,
    /// 4 byte, 5 word, 7/8 array, others nothing
    Collect,
    /// `ReadParametersForNewlyStartedScript`: as Collect, 0 ends the list
    NewScript,
    /// `StoreParameters`: 2/3 variable, 7/8 array, others nothing
    Store,
    /// `GetIndexOfGlobalVariable`: 2 word, 7 array, others nothing (addresses are not dereferenced)
    GlobalIndex,
}

struct Gen {
    r: Rng,
    mission: bool,
    bytes: Vec<u8>,
    /// index variables: global (ScriptSpace bytes 0..16, dword slots) and local (slots 0..4)
    ss_idx: [Option<u32>; 4],
    loc_idx: [Option<u32>; 4],
    /// dereferenced addresses must stay inside the windows
    bounded: bool,
}

impl Gen {
    fn local_limit(&self) -> u32 {
        if self.mission { 64 } else { 40 }
    }
    fn u16(&mut self, v: u32) {
        self.bytes.extend_from_slice(&(v as u16).to_le_bytes());
    }
    fn raw(&mut self, n: usize) {
        for _ in 0..n {
            let b = self.r.next_u32() as u8;
            self.bytes.push(b);
        }
    }
    fn global_loc(&mut self) -> u32 {
        if self.bounded {
            16 + self.r.below(237)
        } else {
            self.r.next_u32() & 0xFFFF
        }
    }
    fn local_loc(&mut self) -> u32 {
        let l = self.local_limit();
        4 + self.r.below(l - 4)
    }
    /// An array operand whose element is a dword of ScriptSpace (`global_elem`) or a local.
    fn array(&mut self, global_elem: bool) {
        let g = self.r.chance(50);
        // global-element arrays use index slots 0/1, local-element arrays 2/3
        let slot = (if global_elem { 0 } else { 2 }) + self.r.below(2) as usize;
        let fresh = if !self.bounded {
            match self.r.below(4) {
                0 => self.r.below(64),
                1 => (self.r.below(64) as i32 - 32) as u32,
                _ => self.r.next_u32(),
            }
        } else if global_elem {
            (self.r.below(45) as i32 - 4) as u32
        } else {
            let k = self.r.below(4);
            if self.r.chance(30) {
                k | (self.r.next_u32() & 0xFFFF_0000)
            } else {
                k
            }
        };
        let tbl = if g { &mut self.ss_idx } else { &mut self.loc_idx };
        let idx = *tbl[slot].get_or_insert(fresh);
        let base = if !self.bounded {
            self.r.next_u32() & 0xFFFF
        } else if global_elem {
            let i = idx as i32;
            let lo = 16.max(4 * i);
            let target = lo + self.r.below((253 - lo) as u32) as i32;
            (target - 4 * i) as u32
        } else {
            let k = idx & 0xFFFF;
            let l = self.local_limit();
            let target = (4 + self.r.below(l - 4)).max(k);
            target - k
        };
        let var = if g { 4 * slot as u32 } else { slot as u32 };
        let flags = (self.r.next_u32() & 0x7FFF) | if g { 0x8000 } else { 0 };
        self.u16(base);
        self.u16(var);
        self.u16(flags);
    }
    fn other_type(&mut self, known: &[u8], zero_ok: bool) -> u8 {
        loop {
            let t = self.r.next_u32() as u8;
            if !known.contains(&t) && (zero_ok || t != 0) {
                return t;
            }
        }
    }
    fn operand(&mut self, mode: Mode) {
        let t = match mode {
            Mode::Collect | Mode::NewScript => {
                if self.r.chance(90) {
                    1 + self.r.below(8) as u8
                } else {
                    self.other_type(&[1, 2, 3, 4, 5, 6, 7, 8], mode == Mode::Collect)
                }
            }
            Mode::Store => {
                if self.r.chance(75) {
                    self.r.pick(&[2u8, 3, 7, 8])
                } else {
                    self.other_type(&[2, 3, 7, 8], true)
                }
            }
            Mode::GlobalIndex => {
                if self.r.chance(80) {
                    self.r.pick(&[2u8, 7])
                } else {
                    self.other_type(&[2, 7], true)
                }
            }
        };
        self.bytes.push(t);
        match (mode, t) {
            (Mode::Store, 2) | (Mode::GlobalIndex, 2) => {
                let l = self.global_loc();
                self.u16(l)
            }
            (Mode::Store, 3) => {
                let l = self.local_loc();
                self.u16(l)
            }
            (Mode::Store, 7) | (Mode::GlobalIndex, 7) => self.array(true),
            (Mode::Store, 8) => self.array(false),
            (Mode::Store, _) | (Mode::GlobalIndex, _) => {}
            (_, 1) | (_, 6) => self.raw(4),
            (_, 2) => {
                let l = self.global_loc();
                self.u16(l)
            }
            (_, 3) => {
                let l = self.local_loc();
                self.u16(l)
            }
            (_, 4) => self.raw(1),
            (_, 5) => self.raw(2),
            (_, 7) => self.array(true),
            (_, 8) => self.array(false),
            _ => {}
        }
    }
}

fn slot(l: &Layout, r: usize, w: usize) -> usize {
    l.word_slot[r][w].expect("raw word")
}

/// Writes `bytes` over the first words of region `r` (the rest of a partial word keeps its bytes).
fn put_bytes(v: &mut [u32], l: &Layout, r: usize, bytes: &[u8]) {
    assert!(bytes.len() <= 4 * WORDS[r], "operand stream too long");
    for (k, c) in bytes.chunks(4).enumerate() {
        let s = slot(l, r, k);
        let mut w = v[s].to_le_bytes();
        w[..c.len()].copy_from_slice(c);
        v[s] = u32::from_le_bytes(w);
    }
}

/// Generates the operand stream (`n` operands, `mode`) and the index variables it reads; sets
/// `m_bIsMission` (half the cases).
fn stream(v: &mut [u32], l: &Layout, mode: Mode, n: usize, bounded: bool) {
    let mut g = Gen {
        r: Rng::new(seed(v)),
        mission: false,
        bytes: Vec::new(),
        ss_idx: [None; 4],
        loc_idx: [None; 4],
        bounded,
    };
    let ms = slot(l, R_S, MISSION_W);
    v[ms] &= !0xFF;
    if g.r.chance(50) {
        v[ms] |= 1 + g.r.below(255);
        g.mission = true;
    }
    for _ in 0..n {
        g.operand(mode);
    }
    if mode == Mode::NewScript {
        g.bytes.push(0);
    }
    put_bytes(v, l, R_CODE, &g.bytes);
    // unused index slots get small values too, so a port that reads the wrong slot reports a
    // mismatch instead of dereferencing a wild host address
    for k in 0..4 {
        let small = g.r.below(4);
        g.ss_idx[k].get_or_insert(small);
        let small = g.r.below(4);
        g.loc_idx[k].get_or_insert(small);
    }
    for (k, x) in g.ss_idx.iter().enumerate() {
        if let Some(x) = x {
            v[slot(l, R_SS, k)] = *x;
        }
    }
    for (k, x) in g.loc_idx.iter().enumerate() {
        if let Some(x) = x {
            let s = if g.mission {
                slot(l, R_ML, k)
            } else {
                slot(l, R_S, LOCALS_W + k)
            };
            v[s] = *x;
        }
    }
}

fn count_arg(l: &Layout) -> usize {
    l.arg_slot[1].unwrap()
}

// ------------------------------------------------------------------ host side

thread_local! {
    static BUF: RefCell<Vec<u8>> = RefCell::new(vec![0u8; 0x20000]);
}

/// The host view of one case.
struct Host {
    base: usize,
}

impl Host {
    /// Host pointer for a guest address in scratch.
    fn p<T>(&self, guest: u32) -> GPtr<T> {
        GPtr::from_addr(self.base.wrapping_add(guest.wrapping_sub(SCRATCH) as usize))
    }
    /// Guest address of a host pointer derived from the view.
    fn g(&self, p: usize) -> u32 {
        SCRATCH.wrapping_add(p.wrapping_sub(self.base) as u32)
    }
}

/// `MISSION_LOCALS` + the 32-bit offset of a host pointer derived from sa-script's host copy.
fn ml_guest(p: usize) -> u32 {
    MISSION_LOCALS.wrapping_add(p.wrapping_sub(vm::MISSION_LOCALS.ptr().addr()) as u32)
}

fn ss_guest(p: usize) -> u32 {
    SCRIPT_SPACE.wrapping_add(p.wrapping_sub(vm::SCRIPT_SPACE.ptr().addr()) as u32)
}

/// How `m_pBaseIP`/`m_pCurrentIP` are handed to the port and read back.
enum Ip {
    /// `m_pCurrentIP` points into scratch (host pointer into the view)
    Current,
    /// `UpdatePC`: `m_pBaseIP` is an integer; the written IP is mapped back with the closure
    Base(fn(&Host, usize) -> u32),
}

/// Runs `f` on a host view of the scratch image with the windows copied into sa-script's host
/// globals, then writes the results back into `c.mem`.
fn on_host<R>(c: &mut Ctx, ip: Ip, f: impl FnOnce(&Host, vm::Scr) -> R) -> R {
    let _g = crate::host_globals();
    BUF.with(|b| {
        let mut b = b.borrow_mut();
        let p0 = b.as_mut_ptr() as usize;
        let a = p0.next_multiple_of(0x1_0000) - p0;
        b[a..a + SCRATCH_LEN].copy_from_slice(&c.mem);
        let h = Host {
            base: b.as_mut_ptr() as usize + a,
        };
        let so = a + c.lay.off[R_S];
        let saved: [u8; 16] = b[so + 0x10..so + 0x20].try_into().unwrap();
        match ip {
            Ip::Current => {
                let gip = c.u(R_S, 5);
                let hip = h.p::<u8>(gip).addr() as u64;
                b[so + 0x14..so + 0x1C].copy_from_slice(&hip.to_le_bytes());
            }
            Ip::Base(_) => {
                let gbase = u64::from(c.u(R_S, 4));
                b[so + 0x10..so + 0x18].copy_from_slice(&gbase.to_le_bytes());
            }
        }
        for k in 0..WORDS[R_SS] {
            vm::SCRIPT_SPACE
                .ptr()
                .cast::<u32>()
                .wrapping_index(k as i32)
                .write(c.u(R_SS, k));
        }
        for k in 0..WORDS[R_ML] {
            vm::MISSION_LOCALS
                .ptr()
                .cast::<u32>()
                .wrapping_index(k as i32)
                .write(c.u(R_ML, k));
        }
        for k in 0..WORDS[R_SP] {
            vm::SCRIPT_PARAMS
                .ptr()
                .cast::<u32>()
                .wrapping_index(k as i32)
                .write(c.u(R_SP, k));
        }
        let s: vm::Scr = h.p(c.addr(R_S));
        let ret = f(&h, s);
        let hip = u64::from_le_bytes(b[so + 0x14..so + 0x1C].try_into().unwrap()) as usize;
        let gip = match ip {
            Ip::Current => h.g(hip),
            Ip::Base(map) => map(&h, hip),
        };
        b[so + 0x10..so + 0x20].copy_from_slice(&saved);
        b[so + 0x14..so + 0x18].copy_from_slice(&gip.to_le_bytes());
        c.mem.copy_from_slice(&b[a..a + SCRATCH_LEN]);
        for k in 0..WORDS[R_SS] {
            c.set_u(
                R_SS,
                k,
                vm::SCRIPT_SPACE
                    .ptr()
                    .cast::<u32>()
                    .wrapping_index(k as i32)
                    .read(),
            );
        }
        for k in 0..WORDS[R_ML] {
            c.set_u(
                R_ML,
                k,
                vm::MISSION_LOCALS
                    .ptr()
                    .cast::<u32>()
                    .wrapping_index(k as i32)
                    .read(),
            );
        }
        for k in 0..WORDS[R_SP] {
            c.set_u(
                R_SP,
                k,
                vm::SCRIPT_PARAMS
                    .ptr()
                    .cast::<u32>()
                    .wrapping_index(k as i32)
                    .read(),
            );
        }
        ret
    })
}

/// The guest address of a local-variable pointer the port returned: into the mission locals when
/// `m_bIsMission` is set, else relative to the scratch view.
fn local_ptr_guest(c: &Ctx, h: &Host, p: usize) -> u32 {
    if c.byte(R_S, 0xDC) != 0 {
        ml_guest(p)
    } else {
        h.g(p)
    }
}

