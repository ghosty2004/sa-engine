const R_S: usize = 0;
const R_CODE: usize = 1;
const R_SS: usize = 2;
const R_ML: usize = 3;
const R_SP: usize = 4;
const R_AUX: usize = 5;
const R_AUX2: usize = 6;
const WORDS: [usize; 7] = [56, 24, 64, 64, 16, 31, 1];

const SCRIPT_SPACE: u32 = 0xA49960;
const MISSION_LOCALS: u32 = 0xA48960;

/// `m_LocalVars` word index in the script region.
const LOCALS_W: usize = 0x3C / 4;
/// The word holding `m_bIsMission` (byte 0xDC).
const MISSION_W: usize = 0xDC / 4;
/// The word holding `m_nLogicalOp` (0xD0, u16) and `m_bNotFlag` (0xD2).
const ANDOR_W: usize = 0xD0 / 4;

fn seed(v: &[u32]) -> u64 {
    let mut h: u64 = 0x5C_21_97;
    for x in v {
        h = (h ^ u64::from(*x)).wrapping_mul(0x100_0000_01B3);
    }
    h
}

/// Guest address of region `r` (the `B::layout` rule).
fn g_addr(r: usize) -> u32 {
    let mut o = 0x10usize;
    for w in &WORDS[..r] {
        o += (4 * w + 0x10 + 0xF) & !0xF;
    }
    (SCRATCH as usize + o) as u32
}

fn machine() -> Vec<Region> {
    let mut s = vec![W::R; WORDS[R_S]];
    s[5] = W::P(R_CODE);
    let mut v = vec![Region {
        words: s,
        kind: Kind::Any,
    }];
    for &n in &WORDS[1..] {
        v.push(raw(n));
    }
    v
}

#[derive(Clone, Copy)]
enum Win {
    Ss,
    Ml,
    Sp,
}

/// Patches the absolute operand (the last four bytes of the instruction at `at`, `len` bytes long)
/// to the scratch window.
fn pat(sites: &[(u32, u32, Win)]) -> Vec<(u32, Vec<u8>)> {
    sites
        .iter()
        .map(|&(at, len, w)| {
            let a = match w {
                Win::Ss => g_addr(R_SS),
                Win::Ml => g_addr(R_ML),
                Win::Sp => g_addr(R_SP),
            };
            (at + len - 4, a.to_le_bytes().to_vec())
        })
        .collect()
}

