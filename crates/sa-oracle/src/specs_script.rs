/// A local index: small (inside `m_LocalVars`) most of the time, any int otherwise.
fn g_loc(r: &mut Rng) -> u32 {
    match r.below(10) {
        0..=5 => r.below(64),
        6 => (r.below(64) as i32 - 32) as u32,
        7 => r.below(0x1_0000),
        _ => r.next_u32(),
    }
}

/// `UpdatePC`'s new IP: a ScriptSpace offset, a negative mission offset, or any int.
fn g_new_ip(r: &mut Rng) -> u32 {
    match r.below(10) {
        0..=3 => r.below(269_000),
        4..=6 => (-(r.below(70_000) as i32)) as u32,
        7 => r.pick(&[0, 1, 0xFFFF_FFFF, 0x8000_0000, 0x7FFF_FFFF]),
        _ => r.next_u32(),
    }
}

fn g_any(r: &mut Rng) -> u32 {
    r.next_u32()
}

fn script_spec(key: &'static str, name: &'static str, addr: u32, ret: crate::specs::RetKind) -> B {
    b(key, name, addr, Thiscall, ret)
        .regions(machine())
        .preserve(PRESERVE_ECX)
        .budget(40_000)
}

