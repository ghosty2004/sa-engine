//! L1 specs for PORT-SCRIPT (`sa_script::vm`, see `docs/arch/script-port.md`): the ten
//! `CRunningScript` VM entries whose hooks declare `preserve = "ecx"` (VER-2: their original callers
//! keep `this` in ECX across the call).
//!
//! Every spec runs on one scratch "machine" of six regions:
//!
//! | region | content |
//! |---|---|
//! | 0 | the `CRunningScript` (0xE0 bytes; `m_pCurrentIP` at 0x14 points at region 1) |
//! | 1 | the operand stream at `m_pCurrentIP` |
//! | 2 | a 256-byte window of `CTheScripts::ScriptSpace` (0xA49960) |
//! | 3 | a 64-dword window of `CTheScripts::LocalVariablesForCurrentMission` (0xA48960) |
//! | 4 | a 16-dword window of `ScriptParams` (0xA43C78) |
//! | 5 | the second script of `ReadParametersForNewlyStartedScript`, `*outBase` of `ReadArrayInformation` |
//! | 6 | `*outIndex` of `ReadArrayInformation` |
//!
//! The original's absolute operands for the three globals (`[reg + 0xA49960]`, `lea [reg*4 +
//! 0xA48960]`, `mov ebx, 0xA43C78`) are patched to the windows wherever it dereferences them; the
//! Rust side gets the same bytes in sa-script's host globals (under [`crate::host_globals`]) and
//! writes them back. Where a function only computes an address (`GetPointerToLocalVariable`,
//! `GetPointerToLocalArrayElement`, `UpdatePC`) nothing is patched and the host pointer is mapped
//! back to the original's address.
//!
//! The operand streams are generated by `fix` with each function's own operand grammar so that
//! every dereferenced variable lies inside its window: global variables at byte offsets 16..=252,
//! locals 4..40 (`m_LocalVars`, the dword at 0xDC is `m_bIsMission`'s) or 4..64 (mission locals),
//! array index variables in the first four slots of either kind (never a store target), with index
//! values that keep `base + index * size` inside the window. Generated values outside that (huge
//! global or local offsets, negative `CollectParameters` counts, which run 65535 slots) cannot be
//! run in scratch memory and are not generated; the address-only functions take any argument.
//!
//! On the host `m_pCurrentIP`/`m_pBaseIP` are 8-byte pointers: the 32-bit words at 0x10..0x20 are
//! saved, the host pointer is stored in their place for the call and the result is translated back
//! (only `m_pCurrentIP` is written by these functions). The scratch view is 64 KiB aligned so the low
//! word of a host address equals the guest's (`GetIndexOfGlobalVariable` returns the low word of
//! `this` for unknown operand types).

