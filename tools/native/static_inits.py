#!/usr/bin/env python3
"""Generate crates/sa-core/src/static_inits.rs: phase B natives for the C++ static initialisers of gta_sa.exe 1.0 US
that follow one of a few fixed instruction shapes (STD-8).

  .venv/bin/python -I tools/native/static_inits.py

Reads the user's exe (SA_GTA_EXE, default re/gta/1.0-US/gta_sa.exe) for the initialiser table `__xc_a..__xc_z`
(0x8A4000..0x8A5A10) and each initialiser's instructions; writes only addresses, names and the shape. Initialisers
already registered elsewhere in crates/*/src (`addr = 0x...` in a `#[hook]` / `#[native]`, or a `(0x..., "...")` row
of a native table) and those of another shape are left out (listed on stderr).
"""
import csv
import os
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/verify'))
os.environ.setdefault('SA_GTA_EXE', str(pathlib.Path.home() / 'sa-engine/re/gta/1.0-US/gta_sa.exe'))
import sadis  # noqa: E402

OUT = ROOT / 'crates/sa-core/src/static_inits.rs'
XC_A, XC_Z = 0x8A4000, 0x8A5A10
ATEXIT = 0x821D1E
VEC_CTOR = 0x821D30
FTOL = 0x821B40

names = {}
for row in csv.reader(open(ROOT / 'catalog/procedures.csv')):
    if row and row[0].startswith('0x'):
        names[int(row[0], 16)] = row[8] or row[3] or f'__init_{row[0][2:]}'

registered = set()
for p in ROOT.glob('crates/*/src/**/*.rs'):
    if p == OUT:
        continue
    t = p.read_text(errors='replace')
    registered |= {int(m, 16) for m in re.findall(r'addr\s*=\s*(0x[0-9A-Fa-f]+)', t)}
    registered |= {int(m, 16) for m in re.findall(r'^\s*\((0x[0-9A-Fa-f]+),\s*"', t, re.M)}


def mem(op):
    m = re.fullmatch(r'(?:dword|word) ptr \[(0x[0-9a-f]+)\]', op)
    return int(m.group(1), 16) if m else None


def imm(op):
    return int(op, 16) if re.fullmatch(r'0x[0-9a-f]+|\d+', op) else None


def shape(a):
    ins = []
    for i in sadis.dis(a, 40):
        ins.append((i.mnemonic, i.op_str))
        if i.mnemonic in ('ret', 'jmp'):
            break
    mn = [m for m, _ in ins]
    ops = [o for _, o in ins]
    m = [mem(o) for o in ops]
    if mn == ['fld', 'fdiv', 'fstp', 'ret'] and None not in m[:3]:
        return 'fdiv', [m[2], m[0], m[1]]
    if mn == ['fld', 'fmul', 'fstp', 'ret'] and None not in m[:3]:
        return 'fmul', [m[2], m[0], m[1]]
    if mn == ['fld', 'fsub', 'fstp', 'ret'] and None not in m[:3]:
        return 'fsub', [m[2], m[0], m[1]]
    if mn == ['fld', 'fmul', 'fdivr', 'fstp', 'ret'] and None not in m[:4]:
        return 'frecip_mul', [m[3], m[0], m[1], m[2]]
    if mn == ['fild', 'fmul', 'fmul', 'call', 'mov', 'ret'] and imm(ops[3]) == FTOL and ops[4].endswith(', eax'):
        d = mem(ops[4].split(',')[0])
        return 'ftol_mul', [d, m[0], m[1], m[2]]
    if mn == ['mov', 'mov', 'ret'] and ops[0].startswith('eax, dword') and ops[1].endswith(', eax'):
        return 'copy32', [mem(ops[1].split(',')[0]), mem(ops[0].split(', ')[1])]
    if mn == ['mov', 'mov', 'ret'] and ops[0].startswith('ax, word') and ops[1].endswith(', ax'):
        return 'copy16', [mem(ops[1].split(',')[0]), mem(ops[0].split(', ')[1])]
    if mn == ['mov', 'call', 'push', 'call', 'pop', 'ret'] and ops[0].startswith('ecx, ') and imm(ops[3]) == ATEXIT:
        return 'ctor_atexit', [imm(ops[0][5:]), imm(ops[1]), imm(ops[2])]
    if mn == ['mov', 'jmp'] and ops[0].startswith('ecx, '):
        return 'tail_ctor', [imm(ops[0][5:]), imm(ops[1])]
    if mn == ['push', 'call', 'pop', 'ret'] and imm(ops[1]) == ATEXIT:
        return 'atexit_only', [imm(ops[0])]
    if mn == ['push'] * 5 + ['call', 'push', 'call', 'pop', 'ret'] and imm(ops[5]) == VEC_CTOR and imm(ops[7]) == ATEXIT:
        dtor, ctor, count, size, ptr = (imm(o) for o in ops[:5])
        return 'vec_ctor_atexit', [ptr, size, count, ctor, dtor, imm(ops[6])]
    return None, ' | '.join(f'{x} {y}' for x, y in ins)


img_slots = sadis.rd(XC_A, XC_Z - XC_A)
slots = [s for (s,) in struct.iter_unpack('<I', img_slots) if s]
rows, other = [], []
for a in slots:
    if a in registered:
        continue
    k, args = shape(a)
    if k is None:
        other.append((a, args))
    else:
        rows.append((a, k, args))

lines = [
    '//! Generated by `tools/native/static_inits.py` (STD-8): phase B natives of the C++ static initialisers of the',
    '//! 1.0 US exe that follow a fixed shape, one table row each (address, catalogue name, shape and operands). The',
    '//! shapes and their semantics are in [`crate::static_init_kinds`]. Regenerate after porting an initialiser',
    '//! elsewhere (rows of registered addresses are left out). Do not edit by hand.',
    '',
    'use crate::static_init_kinds::*;',
    '',
    'static_inits! {',
]
for a, k, args in rows:
    name = names.get(a, f'__init_{a:x}').replace('"', '')
    lines.append(f'    ({a:#x}, "{name}", {k}<{", ".join(hex(x) for x in args)}>),')
lines.append('}')
OUT.write_text('\n'.join(lines) + '\n')
print(f'{len(rows)} rows -> {OUT.relative_to(ROOT)}; {len(other)} other shapes:', file=sys.stderr)
for a, s in other:
    print(f'  {a:#x} {names.get(a, "")}: {s[:160]}', file=sys.stderr)
