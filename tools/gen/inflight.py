"""Collect the registered addresses of every porting branch, so the generator never duplicates a port.

Usage: python3 -I tools/gen/inflight.py [BRANCH...] > tools/gen/exclude_inflight.txt

Reads `master` and every `worktree-agent-*` branch (or only the named branches) with `git cat-file`, plus
the uncommitted `crates/` files of every agent worktree under `.claude/worktrees/`, and prints every
address registered with `#[hook(addr = ...)]` or `#[native(addr = ...)]` (attributes may span lines)
that this checkout's working tree does not register itself (one per line, sorted, with one branch that
registers it). Files written by `tools/gen/patterns.py` (its mark in the file head) do not count: an
older generator branch must not hide its own candidates. `tools/gen/patterns.py` never generates
these addresses.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MAIN = ROOT.split('/.claude/worktrees/')[0]
ATTR = re.compile(r'^[ \t]*#\[(?:hook|native)\(\s*addr\s*=\s*0x([0-9A-Fa-f_]+)', re.M)
GEN_MARK = 'Generated by `tools/gen/patterns.py`'


def git(*args, inp=None):
    r = subprocess.run(['git', '-C', ROOT] + list(args), input=inp, capture_output=True)
    return r.stdout


def addrs_of(text):
    if GEN_MARK in text[:400]:
        return set()
    return {int(m.group(1).replace('_', ''), 16) for m in ATTR.finditer(text)}


BLOBS = {}


def tree_hooks(ref):
    """Registered addresses in the committed tree of `ref` (blobs parsed once across branches)."""
    out = set()
    want = []
    for line in git('ls-tree', '-r', ref, '--', 'crates').decode().splitlines():
        meta, _, path = line.partition('\t')
        parts = meta.split()
        if len(parts) == 3 and parts[1] == 'blob' and path.endswith('.rs'):
            if parts[2] not in BLOBS:
                want.append(parts[2])
            else:
                out |= BLOBS[parts[2]]
    if want:
        data = git('cat-file', '--batch', inp=''.join(s + '\n' for s in want).encode())
        pos = 0
        for sha in want:
            nl = data.index(b'\n', pos)
            hdr = data[pos:nl].split()
            size = int(hdr[2])
            text = data[nl + 1:nl + 1 + size].decode('utf-8', 'replace')
            pos = nl + 1 + size + 1
            BLOBS[sha] = addrs_of(text)
            out |= BLOBS[sha]
    return out


def dir_hooks(d):
    out = set()
    for dirpath, dirs, files in os.walk(d):
        dirs[:] = sorted(x for x in dirs if x != 'target')
        for f in sorted(files):
            if f.endswith('.rs'):
                out |= addrs_of(open(os.path.join(dirpath, f), encoding='utf-8', errors='replace').read())
    return out


def main():
    refs = sys.argv[1:] or ['master'] + sorted(
        git('branch', '--list', 'worktree-agent-*', '--format=%(refname:short)').decode().split())
    base = dir_hooks(os.path.join(ROOT, 'crates'))
    who = {}
    for ref in refs:
        for a in tree_hooks(ref) - base:
            who.setdefault(a, ref)
    wts = os.path.join(MAIN, '.claude', 'worktrees')
    me = os.path.realpath(ROOT)
    for w in sorted(os.listdir(wts)) if os.path.isdir(wts) else []:
        d = os.path.join(wts, w)
        if os.path.realpath(d) == me or not os.path.isdir(os.path.join(d, 'crates')):
            continue
        for a in dir_hooks(os.path.join(d, 'crates')) - base:
            who.setdefault(a, 'worktree ' + w)
    print('# Generator exclusions: addresses registered (#[hook]/#[native]) on master, a worktree-agent-* branch')
    print('# or an agent worktree, but not in this checkout. Regenerate: python3 -I tools/gen/inflight.py')
    for a in sorted(who):
        print('0x%X  # %s' % (a, who[a]))


if __name__ == '__main__':
    main()
