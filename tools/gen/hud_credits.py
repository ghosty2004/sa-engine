"""Generate crates/sa-hud/src/credits_table.rs (PORT-HUD-3): the line / space sequence of
`CCredits::RenderCredits` (0x5A87F0), decoded from the exe bytes. Usage: hud_credits.py REPO_ROOT.

The body between the font setup and `CFont::DrawFonts` is a straight sequence of two shapes; every
instruction must belong to one of them (the script fails otherwise):

  text   push HI; push esi; lea r, [esp+0xC]; push r; push KEY; mov ecx, 0xC1B340;
         [mov [esp+0x14], eax]   (the store of a preceding space)
         call CText::Get; push eax; push SCALE; push SCALE; call CCredits::PrintCreditText
         then `add esp, 0x18`, or a space:
  space  (after a text) fild [esp+0x1C]; mov r, [esp+0x1C]; add esp, 0x18; test r, r; jge +; fadd [2^32];
         fadd [ADD]; call _ftol   (the result is stored into the line offset by the next text), or
         (after a space) test eax, eax; mov [esp+0xC], eax; fild [esp+0xC]; jge +; fadd [2^32];
         fadd [ADD]; call _ftol
"""
import struct
import sys

import capstone
import pefile

ROOT = sys.argv[1]
EXE = '/home/ghosty2004/sa-engine/re/gta/1.0-US/gta_sa.exe'
pe = pefile.PE(EXE, fast_load=True)
IMG = pe.get_memory_mapped_image()
BASE = pe.OPTIONAL_HEADER.ImageBase
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
md.detail = True

START, END = 0x5A888A, 0x5AF8AC  # first `push HI` .. `call CFont::DrawFonts`
THE_TEXT, TEXT_GET, PRINT_CREDIT_TEXT, FTOL, TWO32 = 0xC1B340, 0x6A0050, 0x5A8660, 0x821B40, 0x858C54


def rd(a, n):
    return IMG[a - BASE:a - BASE + n]


def cstr(a):
    s = b''
    while IMG[a - BASE + len(s)] != 0:
        s += bytes([IMG[a - BASE + len(s)]])
    return s.decode('ascii')


ins = list(md.disasm(rd(START, END - START), START))
assert ins[-1].address + ins[-1].size == END, hex(ins[-1].address)
txt = [(i.address, i.mnemonic, i.op_str) for i in ins]
k = 0


def take(mn, op=None):
    global k
    a, m, o = txt[k]
    assert m == mn and (op is None or o == op), (hex(a), m, o, mn, op)
    k += 1
    return o


def imm(o):
    return int(o, 16)


ops = []
pending = False


def store(pushed):
    """The pending space store `mov [esp + 4 + 4 * pushed], eax` (the line offset at entry ESP - 0xC;
    ESP is entry - 0x10 before the text's first push), if it comes next."""
    global k, pending
    d = 4 + 4 * pushed
    d = f'{d:#x}' if d > 9 else str(d)  # capstone's operand format
    if pending and txt[k][1] == 'mov' and txt[k][2] == f'dword ptr [esp + {d}], eax':
        k += 1
        pending = False


def space_tail():
    """`jge +; fadd [2^32]; fadd [ADD]; call _ftol` -> ADD."""
    j = imm(take('jge'))
    take('fadd', f'dword ptr [{TWO32:#x}]')
    assert j == txt[k][0], hex(j)
    add = take('fadd')
    assert add.startswith('dword ptr [0x'), add
    take('call', f'{FTOL:#x}')
    return int(add[len('dword ptr ['):-1], 16)


while k < len(txt):
    # a further space right after one: the intermediate goes through the temp at entry ESP - 4
    while pending and txt[k][1] == 'test':
        take('test', 'eax, eax')
        take('mov', 'dword ptr [esp + 0xc], eax')
        take('fild', 'dword ptr [esp + 0xc]')
        ops.append(('Space', space_tail()))
    store(0)
    hi = imm(take('push'))
    assert hi in (0, 1)
    store(1)
    take('push', 'esi')
    store(2)
    r = take('lea').split(',')[0]
    assert txt[k - 1][2] == f'{r}, [esp + 0xc]', txt[k - 1]
    take('push', r)
    store(3)
    key = imm(take('push'))
    store(4)
    take('mov', f'ecx, {THE_TEXT:#x}')
    store(4)
    assert not pending, hex(txt[k][0])
    take('call', f'{TEXT_GET:#x}')
    take('push', 'eax')
    s1 = imm(take('push'))
    s2 = imm(take('push'))
    assert s1 == s2
    take('call', f'{PRINT_CREDIT_TEXT:#x}')
    ops.append(('Text', key, s1, hi))
    if txt[k][1] == 'add':
        take('add', 'esp, 0x18')
        continue
    take('fild', 'dword ptr [esp + 0x1c]')
    r = take('mov').split(',')[0]
    assert r in ('eax', 'ecx', 'edx') and txt[k - 1][2] == f'{r}, dword ptr [esp + 0x1c]', txt[k - 1]
    take('add', 'esp, 0x18')
    take('test', f'{r}, {r}')
    ops.append(('Space', space_tail()))
    pending = True
assert not pending

lines = [
    '//! Generated by `tools/gen/hud_credits.py` from the exe bytes (PORT-HUD-3); do not edit. The line /',
    '//! space sequence of `CCredits::RenderCredits` (0x5A87F0), in order: GXT key address, scale bits',
    '//! (X and Y alike), highlighted; spaces: the bits of the f32 constant the original adds to the line offset.',
    '',
    'use crate::credits::CreditOp::{self, Space, Text};',
    '',
    f'/// The {len(ops)} steps of `RenderCredits`.',
    '#[rustfmt::skip]',
    f'pub const CREDITS: [CreditOp; {len(ops)}] = [',
]
for o in ops:
    if o[0] == 'Text':
        _, key, s, hi = o
        f = struct.unpack('<f', struct.pack('<I', s))[0]
        lines.append(f'    Text {{ key: 0x{key:X}, scale: 0x{s:08X}, hi: {"true" if hi else "false"} }}, // "{cstr(key)}" {f:g}')
    else:
        f = struct.unpack('<f', rd(o[1], 4))[0]
        bits = struct.unpack('<I', rd(o[1], 4))[0]
        lines.append(f'    Space {{ add: 0x{bits:08X} }}, // + {f:g} (the f32 at 0x{o[1]:X})')
lines.append('];')
open(f'{ROOT}/crates/sa-hud/src/credits_table.rs', 'w').write('\n'.join(lines) + '\n')
print(len(ops), 'ops,', sum(1 for o in ops if o[0] == 'Text'), 'texts')
