#!/usr/bin/env python3
"""Generate crates/sa-core/src/layouts.rs from catalog/layouts.csv (ADR-001 §3).

Every numeric size and offset of the layout table becomes a `usize` constant (`size::T`,
`offset::T__member`); symbolic values (kept verbatim in the CSV) are listed as comments. For the
Rust types that mirror an original layout, ASSERTS adds a compile-time assertion that the Rust size
equals the catalogue's. Types holding pointers are asserted only on 32-bit targets (i686 and wasm32
have the original's 4-byte pointers; a 64-bit phase B build may lay them out natively).

Deterministic: the same CSV gives byte-identical output.

    python3 -I tools/gen/layouts_rs.py            # rewrite the file
    python3 -I tools/gen/layouts_rs.py --check    # exit 1 if the file is stale
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "catalog" / "layouts.csv"
OUT = ROOT / "crates" / "sa-core" / "src" / "layouts.rs"

# (C++ type, Rust type path, holds pointers)
ASSERTS = [
    ("CPool<int32>", "crate::pool::CPool<crate::pool::PedSlot>", True),
    ("CPool<int32>", "crate::pool::CPool<crate::pool::VehicleSlot>", True),
    ("CPool<int32>", "crate::pool::CPool<crate::pool::ObjectSlot>", True),
    ("CCopPed", "crate::pool::PedSlot", False),
    ("CHeli", "crate::pool::VehicleSlot", False),
    ("CCutsceneObject", "crate::pool::ObjectSlot", False),
]

KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
}


def ident(s: str) -> str:
    s = re.sub(r"[^0-9A-Za-z_]+", "_", s).strip("_")
    if not s or s[0].isdigit():
        s = "_" + s
    if s in KEYWORDS:
        s += "_"
    return s


def numeric(v: str):
    try:
        return int(v, 0)
    except ValueError:
        return None


def generate() -> str:
    rows = list(csv.DictReader(SRC.open(newline="")))
    sizes: dict[str, tuple[int, str]] = {}
    offsets: dict[str, tuple[int, str]] = {}
    symbolic: list[str] = []
    conflicts: list[str] = []
    for r in rows:
        where = f"{r['file']}:{r['line']}"
        v = numeric(r["value"])
        if v is None:
            symbolic.append(f"{r['kind']} {r['type']}{'::' + r['member'] if r['member'] else ''} = {r['value']} ({where})")
            continue
        if r["kind"] == "size":
            name, table = ident(r["type"]), sizes
        else:
            name, table = ident(r["type"]) + "__" + ident(r["member"]), offsets
        if name in table and table[name][0] != v:
            conflicts.append(f"{name}: {table[name][0]:#x} ({table[name][1]}) vs {v:#x} ({where})")
            continue
        table.setdefault(name, (v, f"`{r['type']}{'::' + r['member'] if r['member'] else ''}`, {where}"))
    out = [
        "//! Sizes and offsets from `catalog/layouts.csv` (gta-reversed `VALIDATE_SIZE`/`VALIDATE_OFFSET`,",
        "//! CAT-8), with compile-time assertions for the Rust types that mirror an original layout.",
        "//!",
        "//! GENERATED by `tools/gen/layouts_rs.py`; do not edit. Regenerate after the catalogue changes.",
        "#![allow(non_upper_case_globals, dead_code)]",
        "",
        "/// `sizeof(T)` in gta_sa.exe 1.0 US.",
        "pub mod size {",
    ]
    for name in sorted(sizes):
        v, doc = sizes[name]
        out.append(f"    /// {doc}")
        out.append(f"    pub const {name}: usize = {v:#x};")
    out.append("}")
    out.append("")
    out.append("/// `offsetof(T, member)` in gta_sa.exe 1.0 US.")
    out.append("pub mod offset {")
    for name in sorted(offsets):
        v, doc = offsets[name]
        out.append(f"    /// {doc}")
        out.append(f"    pub const {name}: usize = {v:#x};")
    out.append("}")
    if symbolic:
        out.append("")
        out.append("// Symbolic entries (not checked here):")
        out.extend(f"// - {s}" for s in symbolic)
    if conflicts:
        out.append("")
        out.append("// Conflicting duplicates (first kept):")
        out.extend(f"// - {c}" for c in conflicts)
    out.append("")
    out.append("// Rust mirrors of original layouts.")
    for cpp, rust, ptrs in ASSERTS:
        name = ident(cpp)
        if name not in sizes:
            raise SystemExit(f"layouts_rs: {cpp} not in {SRC}")
        if ptrs:
            out.append('#[cfg(target_pointer_width = "32")]')
        out.append(f"const _: () = assert!(core::mem::size_of::<{rust}>() == size::{name});")
    return "\n".join(out) + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; run tools/gen/layouts_rs.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
