#!/usr/bin/env python3
"""Generates the `sa-image` crate's data from gta_sa.exe 1.0 US (ADR-005 §3.2, §3.3).

Writes, under `crates/sa-image/`:

- `image.bin`: the initialised bytes of the arena's sections (`.rdata`, `.data`, `_TEXT_HA`, `_rwdseg`,
  `.rsrc`; 0x858000..0xCB1000) exactly as sa-game's exe image source copies them, with every zero run of
  `GAP` bytes or more left out;
- `src/generated.rs`: the runs of `image.bin` (address, length), the import table (IAT cell, `DLL!name`, in
  IAT order) and the import call sites the sources declare (`orig!`'s `site` form: call site, IAT cell).

Only a developer with the exe runs it; its output is committed. `--check` regenerates in memory and compares
with the committed files; without the exe it checks only that every `site` declaration in the sources has a
call-site entry, and says so.

    .venv/bin/python -I tools/gen/image_rs.py [--check]
"""
import argparse
import hashlib
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'lib'))

CRATE = os.path.join(ROOT, 'crates', 'sa-image')
BIN = os.path.join(CRATE, 'image.bin')
RS = os.path.join(CRATE, 'src', 'generated.rs')
ARENA = (0x858000, 0xCB1000)
GAP = 16
SHA256 = 'a559aa772fd136379155efa71f00c47aad34bbfeae6196b0fe1047d0645cbd26'
SITE_RE = re.compile(r'\b(?:cdecl|stdcall|thiscall|fastcall)\s+site\s+(0x[0-9A-Fa-f_]+)')


def declared_sites():
    out = set()
    for d, _, files in os.walk(os.path.join(ROOT, 'crates')):
        if os.path.join('crates', 'sa-image') in d:
            continue
        for f in files:
            if f.endswith('.rs'):
                for m in SITE_RE.finditer(open(os.path.join(d, f), encoding='utf-8').read()):
                    out.add(int(m.group(1).replace('_', ''), 16))
    return sorted(out)


def arena_bytes(exe):
    img = bytearray(ARENA[1] - ARENA[0])
    raw = open(exe.EXE, 'rb').read()
    for s in exe.pe.sections:
        va = exe.BASE + s.VirtualAddress
        if not ARENA[0] <= va < ARENA[1]:
            continue
        n = s.SizeOfRawData if s.Misc_VirtualSize == 0 else min(s.SizeOfRawData, s.Misc_VirtualSize)
        o = va - ARENA[0]
        img[o:o + n] = raw[s.PointerToRawData:s.PointerToRawData + n]
    return bytes(img)


def runs(img):
    """(address, bytes) of the non-zero stretches; zero gaps shorter than GAP stay inside a run."""
    out, i, n = [], 0, len(img)
    while i < n:
        if img[i] == 0:
            i += 1
            continue
        start, last = i, i
        while i < n:
            if img[i] != 0:
                last = i
            elif i - last >= GAP:
                break
            i += 1
        out.append((ARENA[0] + start, img[start:last + 1]))
        i = last + 1
    return out


def imports(exe):
    """(IAT cell, "DLL!name"), descriptor by descriptor, names from the OriginalFirstThunk arrays."""
    def u32(a):
        return int.from_bytes(exe.IMG[a:a + 4], 'little')

    def cstr(a):
        e = exe.IMG.index(b'\0', a)
        return exe.IMG[a:e].decode('latin-1')

    d = exe.pe.OPTIONAL_HEADER.DATA_DIRECTORY[1].VirtualAddress
    out = []
    while True:
        oft, name, ft = u32(d), u32(d + 12), u32(d + 16)
        if name == 0:
            break
        dll = cstr(name)
        names = oft if oft else ft
        i = 0
        while True:
            t = u32(names + 4 * i)
            if t == 0:
                break
            f = f'#{t & 0xFFFF}' if t & 0x80000000 else cstr(t + 2)
            out.append((exe.BASE + ft + 4 * i, f'{dll}!{f}'))
            i += 1
        d += 20
    return out


def call_sites(exe, sites):
    """(site, cell) of each declared site that is a `call dword ptr [cell]`."""
    out = []
    for s in sites:
        b = exe.rd(s, 6)
        if b[:2] == b'\xff\x15':
            out.append((s, int.from_bytes(b[2:6], 'little')))
        else:
            sys.exit(f'image_rs: site {s:#x} is not a `call dword ptr [cell]` ({b.hex(" ")})')
    return out


def render(rs, imps, sites):
    lines = ['// Generated by tools/gen/image_rs.py from gta_sa.exe 1.0 US; do not edit.', '']
    lines.append(f'pub(crate) static RUNS: [(u32, u32); {len(rs)}] = [')
    lines += [f'    (0x{a:06X}, {len(b)}),' for a, b in rs]
    lines += ['];', '', f'pub static IMPORTS: [(u32, &str); {len(imps)}] = [']
    lines += [f'    (0x{c:06X}, "{n}"),' for c, n in imps]
    lines += ['];', '', f'pub static CALL_SITES: [(u32, u32); {len(sites)}] = [']
    lines += [f'    (0x{s:06X}, 0x{c:06X}),' for s, c in sites]
    lines += ['];', '']
    return '\n'.join(lines)


def check_sites_only():
    have = {int(m, 16) for m in re.findall(r'^\s+\((0x[0-9A-F]+), 0x[0-9A-F]+\),$', open(RS).read().split('CALL_SITES')[1], re.M)}
    missing = [s for s in declared_sites() if s not in have]
    if missing:
        print('differs: site declarations without a call-site entry: ' + ', '.join(f'{s:#x}' for s in missing))
        print('image_rs: run tools/gen/image_rs.py with the exe to regenerate')
        return 1
    print('image_rs: no gta_sa.exe here; checked only that every site declaration has a call-site entry')
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    try:
        import exe
    except (OSError, ImportError) as e:
        if a.check:
            return check_sites_only()
        sys.exit(f'image_rs: cannot read gta_sa.exe ({e})')
    digest = hashlib.sha256(open(exe.EXE, 'rb').read()).hexdigest()
    if digest != SHA256:
        sys.exit(f'image_rs: {exe.EXE} is not gta_sa.exe 1.0 US (SHA-256 {digest})')
    rs = runs(arena_bytes(exe))
    blob = b''.join(b for _, b in rs)
    text = render(rs, imports(exe), call_sites(exe, declared_sites()))
    if a.check:
        bad = [p for p, new in ((BIN, blob), (RS, text.encode())) if not os.path.exists(p) or open(p, 'rb').read() != new]
        for p in bad:
            print(f'differs: {os.path.relpath(p, ROOT)}')
        print(f'image_rs: {len(rs)} runs, {len(blob)} bytes' + ('' if not bad else '; run tools/gen/image_rs.py'))
        return 1 if bad else 0
    os.makedirs(os.path.dirname(RS), exist_ok=True)
    open(BIN, 'wb').write(blob)
    open(RS, 'w').write(text)
    print(f'image_rs: {len(rs)} runs, {len(blob)} bytes in {os.path.relpath(BIN, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
