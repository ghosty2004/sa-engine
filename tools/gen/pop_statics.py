"""PORT-POP-2: generate `crates/sa-pop/src/statics_gen.rs`, the POP "header constant" static initialisers.

Usage: .venv/bin/python -I tools/gen/pop_statics.py [--check]

Reads `re/gta/1.0-US/gta_sa.exe` (never copied into the repo) with objdump and the UNK classification
proposal (`catalog/unk-classification-proposal.csv`, POP rows named `__init_g_* (header constant)`). Each
body must be exactly one of
    fld [a]; fdiv [b]; fstp [g]; ret               g = a / b
    fld [a]; fmul [b]; fstp [g]; ret               g = a * b
    fld [a]; fmul [b]; fdivr [c]; fstp [g]; ret    g = c / (a * b)
(all operands f32 memory), anything else aborts. The initialisers run from the CRT `__xc` table before
D3D sets precision control 24, i.e. under the CRT's PC=53 (as sa-audio's statics): the generated code
computes in f64 and rounds once to f32. For one operation of f32 operands that equals the x87 result
(53 >= 2*24+2); for `c / (a*b)` the product of two f32 is exact in 53 bits, so the same holds.
`--check` regenerates in memory and fails if the file on disk differs.
"""
import csv
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXE = os.environ.get('SA_GTA_EXE', os.path.expanduser('~/sa-engine/re/gta/1.0-US/gta_sa.exe'))
OUT = os.path.join(ROOT, 'crates/sa-pop/src/statics_gen.rs')


def body(addr):
    d = subprocess.run(['objdump', '-d', '-M', 'intel', '--start-address=%#x' % addr,
                        '--stop-address=%#x' % (addr + 0x20), EXE], capture_output=True, text=True, check=True).stdout
    ins = []
    for line in d.splitlines():
        m = re.match(r'\s*([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(.*)', line)
        if not m:
            continue
        ins.append((m.group(2).split(), re.sub(r'\s+', ' ', m.group(3).strip())))
        if m.group(3).startswith('ret'):
            break
    return ins


def mem(op, text):
    m = re.fullmatch(op + r' DWORD PTR ds:0x([0-9a-f]+)', text)
    if not m:
        raise SystemExit('unexpected instruction %r' % text)
    return int(m.group(1), 16)


def main():
    rows = [r for r in csv.DictReader(open(os.path.join(ROOT, 'catalog/unk-classification-proposal.csv')))
            if r['proposed_subsystem'] == 'POP' and r['proposed_name'].endswith('(header constant)')]
    rows.sort(key=lambda r: int(r['address'], 16))
    out = ['//! The POP "header constant" static initialisers (PORT-POP-2): CRT `__xc` initialisers that store a derived',
           '//! f32 constant. GENERATED by `tools/gen/pop_statics.py` from the 1.0 US bytes; do not edit.',
           '//!',
           '//! They run before D3D sets precision control 24 (the CRT\'s PC=53), so each computes in f64 and rounds',
           '//! once to f32, which equals the x87 result for these shapes (see the generator).',
           '',
           'use sa_core::abi::HookReg;',
           'use sa_core::hook;',
           '',
           'use crate::common::g;',
           '',
           'fn rd(a: usize) -> f64 {',
           '    f64::from(g::<f32>(a).read())',
           '}',
           '']
    regs = []
    for r in rows:
        addr = int(r['address'], 16)
        name = r['proposed_name'].split()[0]
        ins = body(addr)
        texts = [t for _, t in ins]
        expect = ' '.join(ins[0][0]).upper()
        if len(ins) == 4 and texts[3] == 'ret':
            a = mem('fld', texts[0])
            g = mem('fstp', texts[2])
            if texts[1].startswith('fdiv '):
                b = mem('fdiv', texts[1])
                expr, doc = 'rd(%#X) / rd(%#X)' % (a, b), '[%#X] / [%#X]' % (a, b)
            elif texts[1].startswith('fmul '):
                b = mem('fmul', texts[1])
                expr, doc = 'rd(%#X) * rd(%#X)' % (a, b), '[%#X] * [%#X]' % (a, b)
            else:
                raise SystemExit('%s: unexpected %r' % (name, texts))
        elif len(ins) == 5 and texts[4] == 'ret':
            a = mem('fld', texts[0])
            b = mem('fmul', texts[1])
            c = mem('fdivr', texts[2])
            g = mem('fstp', texts[3])
            expr, doc = 'rd(%#X) / (rd(%#X) * rd(%#X))' % (c, a, b), '[%#X] / ([%#X] * [%#X])' % (c, a, b)
        else:
            raise SystemExit('%s: unexpected shape %r' % (name, texts))
        if '__init_g_%x' % g != name:
            raise SystemExit('%s stores to %#x' % (name, g))
        fn = 'init_g_%x' % g
        out += ['/// `%s` (%#X): `[%#X] = %s`.' % (name, addr, g, doc),
                '#[hook(addr = %#X, conv = cdecl, name = "%s", expect = "%s")]' % (addr, name, expect),
                'pub fn %s() {' % fn,
                '    g::<f32>(%#X).write((%s) as f32);' % (g, expr),
                '}',
                '']
        regs.append('    HOOK_%s,' % fn.upper())
    out += ['pub const HOOKS: &[HookReg] = &['] + regs + ['];', '']
    text = '\n'.join(out).replace('0X', '0x')
    if '--check' in sys.argv:
        if open(OUT).read() != text:
            raise SystemExit('statics_gen.rs differs from the generator output')
        print('ok')
        return
    open(OUT, 'w').write(text)
    print('%d initialisers' % len(regs))


main()
