#!/usr/bin/env python3
"""One binding per original address (ADR-003 §3.2 / §3.5): the generated `orig!` binding modules.

Usage: python3 -I tools/gen/bindings.py [--check] [--migrate [--dry]] [--report FILE]

Source of truth: `catalog/bindings.csv`, one row per original function that more than one module calls:
address, the crate whose `src/bindings.rs` declares it, the binding's name, its calling convention
(`cdecl` / `stdcall` / `thiscall` / `fastcall` / `reg`, with the `reg("...")` spec), its argument and result
types, and the `=>` target of `orig!` (`unported`, or the path of the Rust port for phases B/C). The generator
writes each crate's `src/bindings.rs` from it (a single `orig!` block, ADR-001 §4: phase A calls the original
address, phases B/C the target); the modules that call such a function import the binding
(`use sa_world::bindings::find_player_ped;`, or `as` their local name) instead of declaring it again.

  (default)  regenerate every `src/bindings.rs` from the CSV;
  --check    regenerate in memory: exit 1 when a `bindings.rs` differs from the CSV, or when an `orig!`
             declaration outside the binding modules repeats a binding exactly (same address, convention,
             types and target: it must import the binding instead). Declarations of a bound address with
             another signature or target (conflicts the migration could not merge without changing a
             caller) are counted and listed with --report, not failed;
  --migrate  build the CSV from the repeated `orig!` declarations in crates/ and rewrite their modules to
             import the bindings (DEDUP-1). `--dry` only reports.

Other generators' output (`Generated by` in the header: patterns.py, ai_patterns.py, ...) keeps its own
declarations; moving those generators onto the bindings is DEDUP-1 step 5's shared generator library.

Which declarations are merged (so that no caller changes behaviour in any phase): the literal-address forms
(`= CONV 0xADDR`, `= reg("...") 0xADDR`) of one address whose convention, `reg` spec, argument and result
types (whitespace-normalised; only primitive types, `GPtr<..>` of them and arrays, so a type name means the
same in every crate) and `=>` target (resolved to an absolute path) are identical, declared in two or more
modules, without attributes, and whose names no `orig::host` stand-in key uses (phase B binds imports by
the declaration's module path). Several such groups at one address: the largest becomes the binding, the
others stay where they are and are reported as conflicts.

Which crate declares a binding: the crate that owns the function (catalogue subsystem, as
`tools/gen/patterns.py` maps it) when every calling crate depends on it; otherwise the highest crate every
calling crate depends on (ADR-003 §3.4's layers; sa-core at worst). A target port must be reachable from
that crate, or the group is not merged. A calling crate that depends on the binding crate only
transitively gets a direct dependency.
"""
