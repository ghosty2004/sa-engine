# ---- source scanning ------------------------------------------------------------------------------
def strip_comments(src):
    """`src` with comments blanked (same length, newlines kept); string literals kept."""
    out, i, n = [], 0, len(src)
    while i < n:
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            out.append(' ' * (j - i))
            i = j
        elif src.startswith('/*', i):
            d, j = 1, i + 2
            while j < n and d:
                if src.startswith('/*', j):
                    d, j = d + 1, j + 2
                elif src.startswith('*/', j):
                    d, j = d - 1, j + 2
                else:
                    j += 1
            out.append(re.sub(r'[^\n]', ' ', src[i:j]))
            i = j
        elif src[i] == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == '\\' else 1
            out.append(src[i:j + 1])
            i = j + 1
        elif src[i] == "'":
            m = re.match(r"'(\\.[^']*|[^\\'])'", src[i:i + 12])
            k = len(m.group(0)) if m else 1
            out.append(src[i:i + k])
            i += k
        else:
            out.append(src[i])
            i += 1
    return ''.join(out)


def close_brace(s, i):
    d = 0
    j = i
    while j < len(s):
        c = s[j]
        if c == '"':
            j += 1
            while j < len(s) and s[j] != '"':
                j += 2 if s[j] == '\\' else 1
        elif c == '{':
            d += 1
        elif c == '}':
            d -= 1
            if d == 0:
                return j
        j += 1
    return len(s) - 1


ENTRY = re.compile(
    r'^(?P<attrs>(?:#\s*\[[^\]]*\]\s*)*)(?P<vis>pub(?:\s*\([^)]*\))?\s+)?fn\s+(?P<name>\w+)\s*\((?P<args>.*?)\)\s*'
    r'(?:->\s*(?P<ret>[^=]+?)\s*)?=\s*(?P<form>.+?)\s*=>\s*(?P<target>[\w:]+)\s*$', re.S)
FORM = re.compile(r'^(?:(?P<conv>cdecl|stdcall|thiscall|fastcall)|reg\(\s*(?P<spec>"[^"]*")\s*\))\s+(?P<addr>0x[0-9A-Fa-f_]+)$')


class Decl:
    def __init__(self, **kw):
        self.__dict__.update(kw)


def norm_type(t):
    return re.sub(r'\s+', '', t or '')


def split_args(a):
    out, d, cur = [], 0, ''
    for c in a:
        if c in '<([':
            d += 1
        elif c in '>)]':
            d -= 1
        if c == ',' and d == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]


def row_args(a):
    """The `name:type` items of a CSV `args` cell (`;`-separated outside brackets: `[u8;4]` stays whole)."""
    out, d, cur = [], 0, ''
    for c in a:
        d += c in '<[('
        d -= c in '>])'
        if c == ';' and d == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    if cur:
        out.append(cur)
    return out


def crate_mod(crate):
    return crate.replace('-', '_')


def scan_file(path):
    """Every `orig!` entry of a file: Decl with spans into the original text."""
    src = open(path, encoding='utf-8').read()
    s = strip_comments(src)
    rel = os.path.relpath(path, ROOT)
    crate = rel.split(os.sep)[1]
    out = []
    for m in re.finditer(r'(?<![\w:])(?:sa_core::)?orig!\s*\{', s):
        if rel.endswith('sa-core/src/orig.rs'):
            break
        b = m.end() - 1
        e = close_brace(s, b)
        body_start = b + 1
        # an attribute on the invocation (`#[cfg(..)] orig! { .. }`) applies to every entry: not merged
        before = s[:m.start()].rstrip()
        battrs = before.endswith(']') and re.search(r'#\s*\[[^\]]*\]$', before.splitlines()[-1].strip() if before else '') is not None
        # inside a `macro_rules!` body (metavariables): not merged
        battrs = battrs or '$' in s[b:e]
        k = body_start
        depth = 0
        start = k
        while k < e:
            c = s[k]
            if c == '"':
                k += 1
                while k < e and s[k] != '"':
                    k += 2 if s[k] == '\\' else 1
            elif c in '([{<':
                depth += 1 if c != '<' else 0
            elif c in ')]}':
                depth -= 1
            elif c == ';' and depth == 0:
                text = s[start:k]
                ent = ENTRY.match(text.strip())
                d = Decl(path=path, rel=rel, crate=crate, block=(m.start(), e + 1), span=(start, k + 1),
                         text=text, ok=False, block_attrs=battrs)
                if ent:
                    d.name = ent.group('name')
                    d.vis = (ent.group('vis') or '').strip()
                    d.attrs = ent.group('attrs').strip()
                    d.args = [norm_type(a.split(':', 1)[1]) for a in split_args(ent.group('args')) if ':' in a]
                    d.argnames = [a.split(':', 1)[0].strip() for a in split_args(ent.group('args')) if ':' in a]
                    d.ret = norm_type(ent.group('ret'))
                    d.target = ent.group('target')
                    f = FORM.match(' '.join(ent.group('form').split()))
                    if f:
                        d.conv = f.group('conv') or 'reg'
                        d.spec = f.group('spec') or ''
                        d.addr = int(f.group('addr').replace('_', ''), 16)
                        d.ok = True
                out.append(d)
                start = k + 1
            k += 1
    return src, out


def generated(p):
    """Another generator's output (its own `orig!` declarations are that generator's business)."""
    with open(p, encoding='utf-8') as fh:
        head = ''.join(fh.readline() for _ in range(10))
    return re.search(r'[Gg]enerated by `tools/', head) is not None


def rust_files():
    for d, dirs, fs in os.walk(CRATES):
        dirs[:] = sorted(x for x in dirs if x != 'target')
        for f in sorted(fs):
            if f.endswith('.rs'):
                yield os.path.join(d, f)


# ---- crates and dependencies ----------------------------------------------------------------------
def direct_deps():
    deps = {}
    for c in sorted(os.listdir(CRATES)):
        p = os.path.join(CRATES, c, 'Cargo.toml')
        if not os.path.exists(p):
            continue
        t = open(p).read()
        ds = set()
        for sec in re.split(r'\n(?=\[)', t):
            head = sec.split('\n', 1)[0]
            if head.endswith('dependencies]') and 'dev-' not in head and 'build-' not in head:
                ds |= set(re.findall(r'^(sa-[a-z0-9-]+)\s*=', sec, re.M))
        deps[c] = ds
    return deps


def closure(deps):
    memo = {}

    def go(c):
        if c not in memo:
            memo[c] = set()
            for d in deps.get(c, ()):
                memo[c] |= {d} | go(d)
        return memo[c]
    for c in deps:
        go(c)
    return memo


# ---- the catalogue ------------------------------------------------------------------------------------
def catalogue():
    rows = {}
    for r in csv.DictReader(open(os.path.join(ROOT, 'catalog', 'procedures.csv'))):
        rows[int(r['address'], 16)] = r
    return rows


def resolve_target(d, deps):
    """Absolute path of a declaration's `=>` target (None when not resolvable here)."""
    t = d.target
    if t == 'unported':
        return 'unported'
    parts = t.split('::')
    if parts[0] == 'crate':
        return crate_mod(d.crate) + '::' + '::'.join(parts[1:])
    if parts[0].startswith('sa_') and parts[0].replace('_', '-') in deps:
        return t
    return None


def target_in(target, crate):
    """`target` (absolute) as written in `crate`."""
    if target == 'unported':
        return target
    head, rest = target.split('::', 1)
    return 'crate::' + rest if head == crate_mod(crate) else target


# ---- migration ------------------------------------------------------------------------------------
def host_names():
    names = set()
    for p in rust_files():
        for k in re.findall(r'"(sa_[a-z_0-9]+(?:::[A-Za-z0-9_]+)+)"', open(p, encoding='utf-8').read()):
            names.add(k.rsplit('::', 1)[1])
    return names


def snake(name):
    n = re.sub(r'[^A-Za-z0-9]+', '_', name)
    n = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', n).lower().strip('_')
    return re.sub(r'_+', '_', n) or 'fn'


def migrate(dry):
    deps = direct_deps()
    trans = closure(deps)
    cat = catalogue()
    hosts = host_names()
    decls = []
    texts = {}
    for p in rust_files():
        if p.endswith(os.sep + 'bindings.rs') or generated(p):
            continue
        src, ds = scan_file(p)
        texts[p] = src
        decls += ds
    by_addr = collections.defaultdict(list)
    for d in decls:
        if d.ok:
            by_addr[d.addr].append(d)
    rows, report = [], []
    chosen = {}  # id(decl) -> row
    stats = collections.Counter()
    stats['addresses declared in more than one file'] = sum(1 for a, ds in by_addr.items() if len({d.rel for d in ds}) > 1)
    for addr in sorted(by_addr):
        ds = by_addr[addr]
        if len({d.rel for d in ds}) < 2:
            continue
        groups = collections.defaultdict(list)
        for d in ds:
            why = None
            if d.attrs or d.block_attrs:
                why = 'attributes'
            elif not all(SIMPLE_TYPE.match(t) for t in d.args + ([d.ret] if d.ret else [])):
                why = 'non-primitive types'
            elif d.name in hosts:
                why = 'host stand-in key'
            tgt = resolve_target(d, deps)
            if tgt is None and not why:
                why = 'relative target path'
            if why:
                stats['not merged: ' + why] += 1
                report.append(f'0x{addr:X}\tkept\t{d.rel}\t{d.name}\t{why}')
                continue
            groups[(d.conv, d.spec, tuple(d.args), d.ret, tgt)].append(d)
        if not groups:
            continue
        key, best = max(groups.items(), key=lambda kv: (len({d.rel for d in kv[1]}), len(kv[1])))
        for k, g in groups.items():
            if k is not key:
                stats['not merged: signature or target conflict'] += len(g)
                for d in g:
                    report.append(f'0x{addr:X}\tconflict\t{d.rel}\t{d.name}\t{d.conv} {d.spec} ({", ".join(d.args)}) -> {d.ret or "()"} => {d.target}'
                                  f' (binding: {key[0]} {key[1]} ({", ".join(key[2])}) -> {key[3] or "()"} => {key[4]})')
        if len({d.rel for d in best}) < 2:
            continue
        users = {d.crate for d in best}
        r = cat.get(addr)
        owner = SUBSYS_CRATE.get(r['subsystem']) if r else None
        reach = lambda c: all(c == u or c in trans.get(u, ()) for u in users)
        if not (owner and reach(owner)):
            cands = [c for c in deps if all(c == u or c in trans.get(u, ()) for u in users)]
            if not cands:
                stats['not merged: no common crate'] += len(best)
                continue
            # the highest of them: the one that depends on most of the others
            owner = max(sorted(cands), key=lambda c: len(trans.get(c, ())))
        tgt = key[4]
        if tgt != 'unported':
            tc = tgt.split('::', 1)[0].replace('_', '-')
            if tc != owner and tc not in trans.get(owner, ()):
                stats['not merged: target not reachable from the binding crate'] += len(best)
                for d in best:
                    report.append(f'0x{addr:X}\tkept\t{d.rel}\t{d.name}\ttarget {tgt} not reachable from {owner}')
                continue
        names = collections.Counter(d.name for d in best)
        name = sorted(names.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
        argnames = best[0].argnames
        row = {'address': f'0x{addr:X}', 'crate': owner, 'name': name, 'conv': key[0], 'spec': key[1],
               'args': ';'.join(f'{n}:{t}' for n, t in zip(argnames, key[2])), 'ret': key[3], 'target': tgt,
               'catalogue_name': (r.get('name') or r.get('gr_name') or r.get('ghidra_name') or '') if r else ''}
        rows.append(row)
        for d in best:
            chosen[id(d)] = row
        stats['bindings'] += 1
        stats['declarations replaced'] += len(best)
    # unique names per crate
    seen = collections.defaultdict(dict)
    for row in rows:
        c = seen[row['crate']]
        if row['name'] in c:
            row['name'] = f"{row['name']}_{int(row['address'], 16):x}"
        c[row['name']] = row
    if dry:
        return rows, report, stats
    # rewrite the callers
    need_dep = collections.defaultdict(set)
    byfile = collections.defaultdict(list)
    for d in decls:
        if id(d) in chosen:
            byfile[d.path].append(d)
    for p, ds in byfile.items():
        src = texts[p]
        s = strip_comments(src)
        crate = ds[0].crate
        edits = []
        blocks = collections.defaultdict(list)
        for d in ds:
            blocks[d.block].append(d)
        for (bs, be), bd in blocks.items():
            uses = []
            for d in bd:
                row = chosen[id(d)]
                path = ('crate' if row['crate'] == crate else crate_mod(row['crate'])) + '::bindings::' + row['name']
                if row['crate'] != crate and row['crate'] not in deps[crate]:
                    need_dep[crate].add(row['crate'])
                vis = (d.vis + ' ') if d.vis else ''
                uses.append(f'{vis}use {path}{"" if row["name"] == d.name else " as " + d.name};')
                a, b = d.span
                # the entry with its doc comments (the text before it since the previous `;` / `{`)
                edits.append((a, b, ''))
            ls = src.rfind('\n', 0, bs) + 1
            indent = re.match(r'[ \t]*', src[ls:bs]).group(0)
            # remaining entries in the block?
            spans = sorted(d.span for d in bd)
            rest = s[bs:be]
            for a, b in spans:
                rest = rest.replace(s[a:b], '', 1)
            body = rest[rest.index('{') + 1:rest.rindex('}')]
            ins = ''.join(f'{indent}{u}\n' for u in sorted(set(uses)))
            if not body.strip():
                # the whole invocation (and its doc / attribute lines) goes
                edits = [e for e in edits if not (bs <= e[0] < be)]
                end = be
                if src[end:end + 1] == ';':
                    end += 1
                if src[end:end + 1] == '\n':
                    end += 1
                edits.append((ls, end, ins))
            else:
                edits.append((ls, ls, ins))
        src2 = src
        for a, b, new in sorted(edits, key=lambda e: (e[0], e[1]), reverse=True):
            if a == b:
                src2 = src2[:a] + new + src2[a:]
            else:
                # keep the newline before the next entry tidy
                seg = src2[a:b]
                src2 = src2[:a] + (new if new else ('\n' if seg.endswith('\n') and False else '')) + src2[b:]
        src2 = re.sub(r'\{\s*\n(\s*\n)+', '{\n', src2)
        src2 = re.sub(r'\n[ \t]*\n([ \t]*\n)+', '\n\n', src2)
        open(p, 'w', encoding='utf-8').write(src2)
    for crate, add in need_dep.items():
        p = os.path.join(CRATES, crate, 'Cargo.toml')
        t = open(p).read()
        for a in sorted(add):
            t = re.sub(r'(\[dependencies\]\n)', r'\1%s = { path = "../%s" }\n' % (a, a), t, count=1)
        open(p, 'w').write(t)
    rows.sort(key=lambda r: (r['crate'], int(r['address'], 16)))
    with open(CSV, 'w', newline='') as fh:
        w = csv.DictWriter(fh, FIELDS, lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    return rows, report, stats


# ---- generation -------------------------------------------------------------------------------------
def load_rows():
    if not os.path.exists(CSV):
        return []
    return list(csv.DictReader(open(CSV)))


X87_TYPES = ('sa_math::x87::X87', 'X87')


def x87_spec(r):
    """A `cdecl` / `stdcall` / `thiscall` function returning the full 80-bit ST0 (`X87`): `orig!`'s plain forms
    round ST0 to an `f64`, so the binding goes through the register convention (`regconv`), which keeps all 80
    bits: `reg("args = [ecx] stack..[; pop]")`, the same arguments and stack cleanup as the convention."""
    n = len([a for a in row_args(r['args']) if a])
    regs = ['ecx'] if r['conv'] == 'thiscall' else []
    stack = n - len(regs)
    words = ' '.join(regs + ['stack'] * stack) or 'stack'
    pop = '; pop' if r['conv'] in ('stdcall', 'thiscall') and stack else ''
    if not regs and not stack:
        return '"args = stack"'
    return f'"args = {words}{pop}"'


def render(crate, rows):
    """One `orig!` invocation per binding (a single large block would exceed the macro recursion limit)."""
    s = HEADER
    own = re.compile(r'(?<![\w:])%s::' % crate_mod(crate))
    for r in sorted(rows, key=lambda r: int(r['address'], 16)):
        # types by absolute path (`GPtr<sa_stream::shared::CBaseModelInfo>`) are `crate::` paths in their own crate
        args = own.sub('crate::', ', '.join(a.replace(':', ': ', 1) for a in row_args(r['args']) if a))
        ret = f' -> {own.sub("crate::", r["ret"])}' if r['ret'] else ''
        form = f'reg({r["spec"]}) {r["address"]}' if r['conv'] == 'reg' else f'{r["conv"]} {r["address"]}'
        if r['conv'] != 'reg' and r['ret'] in X87_TYPES:
            form = f'reg({x87_spec(r)}) {r["address"]}'
        cn = r['catalogue_name'] or 'FUN_%08x' % int(r['address'], 16)
        s += '\norig! {\n'
        s += f'    /// `{cn}` ({r["address"]})\n'
        s += f'    pub fn {r["name"]}({args}){ret} = {form} => {target_in(r["target"], crate)};\n'
        s += '}\n'
    return s


def twin_rows(rows):
    """The ported twins: a binding whose crate lies below its port's crate (`port` column, a caller in a lower
    layer reaches the port through the phase B registry) is also declared in the port's crate, with the port as
    its `=>` target, for the callers that may depend on that crate."""
    names = collections.defaultdict(set)
    for r in rows:
        names[r['crate']].add(r['name'])
    out = []
    for r in sorted(rows, key=lambda r: int(r['address'], 16)):
        if not r.get('port'):
            continue
        pc = r['port'].split('::', 1)[0].replace('_', '-')
        t = dict(r)
        t['crate'], t['target'], t['port'] = pc, r['port'], ''
        if t['name'] in names[pc]:
            t['name'] = f"{r['name']}_{int(r['address'], 16):x}"
        names[pc].add(t['name'])
        out.append(t)
    return out


def generate(check):
    rows = load_rows()
    by = collections.defaultdict(list)
    for r in rows + twin_rows(rows):
        by[r['crate']].append(r)
    bad = []
    for crate in sorted(set(by) | {c for c in os.listdir(CRATES) if os.path.exists(os.path.join(CRATES, c, 'src', 'bindings.rs'))}):
        path = os.path.join(CRATES, crate, 'src', 'bindings.rs')
        text = render(crate, by.get(crate, [])) if by.get(crate) else None
        old = open(path).read() if os.path.exists(path) else None
        if check:
            if old != text:
                bad.append(f'{path}: differs from catalog/bindings.csv (run tools/gen/bindings.py)')
            continue
        if text is None:
            if old is not None:
                os.remove(path)
            continue
        if old != text:
            open(path, 'w').write(text)
        lib = os.path.join(CRATES, crate, 'src', 'lib.rs')
        lt = open(lib).read()
        if not re.search(r'^pub mod bindings;', lt, re.M):
            # after the crate attributes and docs, before the first item
            m = re.search(r'^(pub mod|mod|use|pub use|#\[cfg|extern crate|macro_rules)', lt, re.M)
            i = m.start() if m else len(lt)
            lt = lt[:i] + '/// The `orig!` bindings this crate declares for the whole workspace (generated, ADR-003 §3.2).\npub mod bindings;\n' + lt[i:]
            open(lib, 'w').write(lt)
    return rows, bad


def check_redeclared(rows):
    """Declarations outside the binding modules that repeat a binding exactly, and the other ones of bound addresses."""
    deps = direct_deps()
    hosts = host_names()
    bound = {int(r['address'], 16): r for r in rows}
    exact, other = [], []
    for p in rust_files():
        if p.endswith(os.sep + 'bindings.rs') or generated(p):
            continue
        _, ds = scan_file(p)
        for d in ds:
            if not d.ok or d.addr not in bound:
                continue
            r = bound[d.addr]
            same = (d.conv == r['conv'] and d.spec == r['spec'] and
                    ';'.join(d.args) == ';'.join(a.split(':', 1)[1] for a in row_args(r['args']) if a) and
                    d.ret == r['ret'] and resolve_target(d, deps) == r['target'] and not d.attrs
                    and not d.block_attrs and d.name not in hosts)
            (exact if same else other).append(f'{d.rel}: {d.name} = 0x{d.addr:X}')
    return exact, other


def main():
    rep = sys.argv[sys.argv.index('--report') + 1] if '--report' in sys.argv else None
    if '--repoint' in sys.argv:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        sys.path.insert(0, os.path.join(ROOT, 'tools', 'lib'))
        import bindings_migrate
        stats = bindings_migrate.repoint(sys.argv[sys.argv.index('--repoint') + 1], '--dry' in sys.argv)
        for k, v in sorted(stats.items()):
            print(f'{k}: {v}')
        if '--dry' in sys.argv:
            return 0
    if '--twin' in sys.argv:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        sys.path.insert(0, os.path.join(ROOT, 'tools', 'lib'))
        import bindings_migrate
        stats = bindings_migrate.twin(sys.argv[sys.argv.index('--twin') + 1], '--dry' in sys.argv)
        for k, v in sorted(stats.items()):
            print(f'{k}: {v}')
        if '--dry' in sys.argv:
            return 0
    if '--resolve' in sys.argv:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import bindings_migrate
        stats = bindings_migrate.resolve('--dry' in sys.argv, rep)
        for k, v in sorted(stats.items()):
            print(f'{k}: {v}')
        if '--dry' in sys.argv:
            return 0
    if '--migrate' in sys.argv:
        rows, report, stats = migrate('--dry' in sys.argv)
        for k, v in sorted(stats.items()):
            print(f'{k}: {v}')
        if rep:
            open(rep, 'w').write('address\tkind\tfile\tname\tdetail\n' + '\n'.join(report) + '\n')
        if '--dry' in sys.argv:
            return 0
    check = '--check' in sys.argv
    rows, bad = generate(check)
    exact, other = check_redeclared(rows)
    for e in exact:
        bad.append(f'{e}: repeats the binding in catalog/bindings.csv (import it)')
    print(f'bindings: {len(rows)} in {len({r["crate"] for r in rows})} crates; '
          f'{len(other)} other declarations of bound addresses (signature or target conflicts)')
    if rep and not any(a in sys.argv for a in ('--migrate', '--resolve', '--repoint', '--twin')):
        open(rep, 'w').write('\n'.join(other) + '\n')
    for b in bad:
        print('FAIL', b)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
