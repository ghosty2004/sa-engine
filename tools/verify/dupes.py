#!/usr/bin/env python3
"""Duplicated helper code across crates (ADR-003 §3.2, §4).

Usage: python3 -I tools/verify/dupes.py [--names] [--bodies] [--min-crates N] [--all-files]
                                         [--include-tests] [--fn NAME] [--summary]

Scans every `*.rs` under crates/ and samp-rs/crates/ for free function definitions (module-level,
nested in `mod`, or nested in another fn body; not methods of an `impl` / `trait`, not inside a
macro invocation such as `orig! { ... }` or a `macro_rules!` body, so the `orig!` bindings are not
counted: tools/gen/bindings.py checks those). Two reports:

  names   a function name defined in two or more crates (default: at least --min-crates 2), with the
          number of crates and files and every location;
  bodies  two or more definitions in different crates (or files, with --all-files) whose
          signatures and bodies are identical after comments and whitespace are stripped (with
          --renamed: also after parameter / generic / local names, generic bounds, path prefixes,
          integer spellings and implied turbofish are normalised, tools/verify/helpernorm.py).

Excluded by default: generated files (a header comment "Generated by" / "generated by" in the first
10 lines; their helpers come from the generator, which is fixed instead), `#[cfg(test)]` modules and
`tests/` / `benches/` / `examples/` directories and ports (`#[hook]` / `#[native]` functions: one per
original address, identical bodies at different addresses are not copies) (--include-tests counts
them), and the names in
COMMON (constructors, trait-like names, `main`) for the names report.

`--summary` prints one line per name with its crate/file counts (the measure ADR-003 §1 quotes).

`--check` (the writer gate's `dupes` step, ADR-003 §4): the cross-crate groups of `--bodies --renamed` must
each be listed in `tools/verify/dupes-allow.txt` (one line per group: its members `file:fn` sorted and joined
with `;`, a tab, the reason the copies stay: different semantics, separate workspaces, ...). Exit 1 on a group
not listed (a new copy: import the existing definition instead) and on a listed group that no longer exists
(the list only shrinks: remove the line). `--write-allow` rewrites the list from the tree, keeping the reasons
of the groups it already lists (new groups get `pending: ...`). Without `--check` the exit status is 0.
"""
import argparse
import collections
import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import helpernorm  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SCAN = ['crates', os.path.join('samp-rs', 'crates')]
COMMON = {
    'main', 'new', 'default', 'from', 'into', 'drop', 'fmt', 'clone', 'eq', 'cmp', 'hash', 'build',
    'run', 'init', 'test', 'tests', 'parse', 'read', 'write', 'get', 'set', 'len', 'is_empty', 'deref',
    'deref_mut', 'index', 'next', 'reset', 'update', 'process', 'render', 'create', 'load', 'save',
}
GENERATED = re.compile(r'[Gg]enerated by|Do not edit by hand|DO NOT EDIT')


def strip(src):
    """Source with comments, string and char literals blanked (same length, newlines kept)."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            out.append(' ' * (j - i))
            i = j
        elif src.startswith('/*', i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith('/*', j):
                    depth, j = depth + 1, j + 2
                elif src.startswith('*/', j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            out.append(re.sub(r'[^\n]', ' ', src[i:j]))
            i = j
        elif c == 'r' and re.match(r'r#*"', src[i:i + 8]) and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == '_')):
            m = re.match(r'r(#*)"', src[i:])
            end = src.find('"' + m.group(1), i + len(m.group(0)))
            end = n if end < 0 else end + 1 + len(m.group(1))
            out.append('"' + re.sub(r'[^\n]', ' ', src[i + 1:end - 1]) + '"')
            i = end
        elif c == '"' or (c == 'b' and src.startswith('b"', i)):
            j = i + (2 if c == 'b' else 1)
            while j < n and src[j] != '"':
                j += 2 if src[j] == '\\' else 1
            out.append('"' + re.sub(r'[^\n]', ' ', src[i + 1:j]) + '"')
            i = j + 1
        elif c == "'":
            m = re.match(r"'(\\.[^']*|[^\\'])'", src[i:i + 12])
            if m:
                out.append("'" + ' ' * (len(m.group(0)) - 2) + "'")
                i += len(m.group(0))
            else:  # a lifetime or label
                out.append(c)
                i += 1
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def match_brace(s, i):
    """Index after the bracket closing the one at s[i] ('{', '(' or '[')."""
    pairs = {'{': '}', '(': ')', '[': ']'}
    stack = [pairs[s[i]]]
    j = i + 1
    while j < len(s) and stack:
        c = s[j]
        if c in pairs:
            stack.append(pairs[c])
        elif stack and c == stack[-1]:
            stack.pop()
        j += 1
    return j


ITEM = re.compile(
    r'\b(?:(?P<macro>[A-Za-z_][A-Za-z0-9_:]*)\s*!\s*(?:[A-Za-z_][A-Za-z0-9_]*\s*)?(?P<mopen>[{(\[])'
    r'|(?P<kw>impl|trait)\b'
    r'|(?P<mod>mod)\s+(?P<modname>[A-Za-z_][A-Za-z0-9_]*)\s*\{'
    r'|(?P<fn>fn)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*))')
CFG_TEST = re.compile(r'#\s*\[\s*cfg\s*\(([^\]]*)\]\s*(?:#\s*\[[^\]]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?mod\s*$')


PORT_ATTR = re.compile(r'#\s*\[\s*(?:[a-z_]+::)*(?:hook|native)\s*\(')


def scan_block(s, start, end, out, in_test):
    """Collects free fns in s[start:end] (a module or fn body)."""
    i = start
    while i < end:
        m = ITEM.search(s, i, end)
        if not m:
            return
        if m.group('macro'):
            # macro invocation or macro_rules! definition: skip its body entirely
            i = match_brace(s, m.start('mopen'))
            continue
        if m.group('kw'):
            # impl / trait block: skip to its body and past it (methods are not free fns)
            b = s.find('{', m.end(), end)
            semi = s.find(';', m.end(), end)
            if b < 0 or (0 <= semi < b):
                i = m.end()
                continue
            i = match_brace(s, b)
            continue
        if m.group('mod'):
            b = m.end() - 1
            close = match_brace(s, b)
            head = s[max(0, m.start() - 300):m.start() + 3]
            cm = CFG_TEST.search(head)
            test = in_test or bool(cm and re.search(r'\btest\b', cm.group(1)) and 'not(test' not in cm.group(1))
            scan_block(s, b + 1, close - 1, out, test)
            i = close
            continue
        # fn NAME ... { body } or ; (trait/extern declaration)
        j = m.end()
        depth = 0
        while j < end:
            c = s[j]
            if c in '([<':
                if c == '<' and s[j - 1] == '-':
                    j += 1
                    continue
                depth += 1
            elif c in ')]>':
                if c == '>' and s[j - 1] == '-':
                    j += 1
                    continue
                depth -= 1
            elif c == '{' and depth <= 0:
                break
            elif c == ';' and depth <= 0:
                break
            j += 1
        if j >= end or s[j] == ';':
            i = j + 1
            continue
        close = match_brace(s, j)
        prev = max(s.rfind('}', start, m.start()), s.rfind(';', start, m.start()), start)
        port = bool(PORT_ATTR.search(s, prev, m.start()))
        out.append((m.group('name'), m.start('fn'), j, close, in_test or port))
        scan_block(s, j + 1, close - 1, out, in_test)
        i = close


def files():
    for top in SCAN:
        base = os.path.join(ROOT, top)
        for d, dirs, fs in os.walk(base):
            dirs[:] = sorted(x for x in dirs if x not in ('target', '.git'))
            for f in sorted(fs):
                if f.endswith('.rs'):
                    yield os.path.join(d, f)


def crate_of(path):
    rel = os.path.relpath(path, ROOT).split(os.sep)
    if rel[0] == 'samp-rs':
        return 'samp-rs/' + rel[2]
    return rel[1]


def collect(include_tests):
    defs = []  # (name, crate, rel, line, sig+body normalised, generated)
    for path in files():
        rel = os.path.relpath(path, ROOT)
        parts = rel.split(os.sep)
        test_dir = any(p in ('tests', 'benches', 'examples') for p in parts[:-1])
        if test_dir and not include_tests:
            continue
        with open(path, encoding='utf-8', errors='replace') as fh:
            src = fh.read()
        generated = bool(GENERATED.search('\n'.join(src.splitlines()[:10])))
        s = strip(src)
        found = []
        scan_block(s, 0, len(s), found, False)
        for name, fs, bo, close, skip in found:
            if skip and not include_tests:
                continue
            # signature from `fn` (visibility and attributes ignored) to the end of the body
            text = ' '.join(s[fs:close].split())
            line = s.count('\n', 0, fs) + 1
            defs.append((name, crate_of(path), rel, line, text, generated))
    return defs


ALLOW = os.path.join(ROOT, 'tools', 'verify', 'dupes-allow.txt')


def renamed_groups(include_tests=False):
    """The cross-crate groups of definitions identical modulo renaming (non-generated)."""
    defs = [d for d in collect(include_tests) if not d[5]]
    by_body = collections.defaultdict(list)
    for d in defs:
        body = helpernorm.normalise(d[4][d[4].index(d[0]) + len(d[0]):])
        by_body[hashlib.sha1(body.encode()).hexdigest()].append(d)
    return [ds for ds in by_body.values() if len({d[1] for d in ds}) >= 2 and len(ds[0][4]) >= 40]


def group_key(ds):
    return ';'.join(sorted({f'{d[2]}:{d[0]}' for d in ds}))


def read_allow():
    out = {}
    if os.path.exists(ALLOW):
        for line in open(ALLOW, encoding='utf-8'):
            if line.strip() and not line.startswith('#'):
                k, _, why = line.rstrip('\n').partition('\t')
                out[k] = why
    return out


def check(write):
    groups = renamed_groups()
    allow = read_allow()
    keys = {group_key(ds): ds for ds in groups}
    if write:
        with open(ALLOW, 'w', encoding='utf-8') as fh:
            fh.write('# Cross-crate copies that stay, with the reason (tools/verify/dupes.py --check); the list only shrinks.\n')
            for k in sorted(keys):
                fh.write(f'{k}\t{allow.get(k) or "pending: not yet merged (DEDUP-1)"}\n')
        print(f'dupes: allow-list written, {len(keys)} groups')
        return 0
    new = [k for k in keys if k not in allow]
    stale = [k for k in allow if k not in keys]
    print(f'dupes: {len(keys)} cross-crate groups of copies, {len(keys) - len(new)} listed in tools/verify/dupes-allow.txt; '
          f'{len(new)} new, {len(stale)} stale')
    for k in new:
        print(f'FAIL new copies: {k} (import the existing definition, ADR-003 §3.2)')
    for k in stale:
        print(f'FAIL stale allow-list line (the group changed or is gone; remove or update it): {k}')
    return 1 if new or stale else 0


def main():
    if '--check' in sys.argv or '--write-allow' in sys.argv:
        return check('--write-allow' in sys.argv)
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--names', action='store_true', help='only the same-name report')
    ap.add_argument('--bodies', action='store_true', help='only the identical-body report')
    ap.add_argument('--min-crates', type=int, default=2)
    ap.add_argument('--all-files', action='store_true',
                    help='identical bodies in different files of one crate count too')
    ap.add_argument('--include-tests', action='store_true')
    ap.add_argument('--include-generated', action='store_true')
    ap.add_argument('--renamed', action='store_true', help='match bodies modulo renaming (helpernorm.py)')
    ap.add_argument('--fn', action='append', default=[], help='only these names (repeatable)')
    ap.add_argument('--summary', action='store_true', help='one line per name: crates, files')
    a = ap.parse_args()
    defs = [d for d in collect(a.include_tests) if a.include_generated or not d[5]]
    if a.fn:
        defs = [d for d in defs if d[0] in a.fn]
    both = not (a.names or a.bodies)

    by_name = collections.defaultdict(list)
    for d in defs:
        by_name[d[0]].append(d)
    if both or a.names:
        rows = []
        for name, ds in by_name.items():
            if name in COMMON and not a.fn:
                continue
            crates = sorted({d[1] for d in ds})
            if len(crates) >= a.min_crates:
                rows.append((len(crates), len({d[2] for d in ds}), name, ds))
        rows.sort(key=lambda r: (-r[0], -r[1], r[2]))
        print(f'# names defined in >= {a.min_crates} crates: {len(rows)}')
        for nc, nf, name, ds in rows:
            if a.summary:
                print(f'{name:28} crates={nc:<3} files={nf}')
                continue
            print(f'{name}: {nc} crates, {nf} files')
            for d in sorted(ds, key=lambda d: (d[2], d[3])):
                print(f'    {d[2]}:{d[3]}')
    if both or a.bodies:
        by_body = collections.defaultdict(list)
        for d in defs:
            # the name is part of the text; also group renamed copies by the text without the name
            body = d[4][d[4].index(d[0]) + len(d[0]):]
            if a.renamed:
                body = helpernorm.normalise(body)
            by_body[hashlib.sha1(body.encode()).hexdigest()].append(d)
        groups = []
        for ds in by_body.values():
            key = (lambda d: d[2]) if a.all_files else (lambda d: d[1])
            if len({key(d) for d in ds}) < 2 or len(ds[0][4]) < 40:
                continue
            groups.append(ds)
        groups.sort(key=lambda ds: (-len({d[1] for d in ds}), -len(ds), ds[0][0]))
        print(f'# identical bodies across {"files" if a.all_files else "crates"}: {len(groups)} groups, '
              f'{sum(len(g) - 1 for g in groups)} redundant copies')
        for ds in groups:
            names = sorted({d[0] for d in ds})
            print(f'{"/".join(names)}: {len(ds)} copies in {len({d[1] for d in ds})} crates')
            if not a.summary:
                for d in sorted(ds, key=lambda d: (d[2], d[3])):
                    print(f'    {d[2]}:{d[3]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
